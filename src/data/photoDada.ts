const firstWeightTotal = dateWeights.slice(0, anchorIndex).reduce((total, weight) => total + weight, 0)
const secondWeightTotal = dateWeights.slice(anchorIndex).reduce((total, weight) => total + weight, 0)
let firstAccumulatedWeight = 0
let secondAccumulatedWeight = 0

export const PHOTOS: Photo[] = PHOTO_ITEMS.map((photo, index) => {
    let timestamp: number
    if (index <= anchorIndex) {
        if (index > 0) firstAccumulatedWeight += dateWeights[index - 1]
        timestamp = startDate + Math.floor((firstAccumulatedWeight / firstWeightTotal) * firstDayRange) * 86_400_000
    } else {
        secondAccumulatedWeight += dateWeights[index - 1]
        timestamp = anchorDate + Math.floor((secondAccumulatedWeight / secondWeightTotal) * secondDayRange) * 86_400_000
    }
    const src = PHOTO_THUMB_SOURCES[index] ?? photo.src
    return {
        ...photo,
        src,
        date: (src && PHOTO_DATE_OVERRIDES[src]) || new Date(timestamp).toISOString().slice(0, 10),
    }
})